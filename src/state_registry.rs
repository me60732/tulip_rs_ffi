    #[test]
    fn test_state_serialize_errors() {
        unsafe {
            // Null state ptr -> null CBytes
            let bytes = tulip_state_serialize(
                CIndicatorId::Adx as u32,
                CStateFormat::Bincode as u32,
                std::ptr::null(),
            );
            assert!(bytes.ptr.is_null());

            let state = adx_state();

            // Unknown indicator id -> null CBytes
            let bytes = tulip_state_serialize(999, CStateFormat::Bincode as u32, state);
            assert!(bytes.ptr.is_null());

            // Valid id but wrong format (7) -> null CBytes
            let bytes = tulip_state_serialize(CIndicatorId::Adx as u32, 7, state);
            assert!(bytes.ptr.is_null());

            // A hash-shaped id of some OTHER indicator is "valid" for
            // serialize, but must not type-pun an adx state: it would
            // reinterpret the box. Guard: this call with Rsi's id on an
            // Adx state is UB per # Safety (caller error), so we only
            // assert unknown ids error out. (Deserialize cannot make this
            // mistake: the blob's own name wins.)
            crate::adx::adx_state_free(state);
        }
    }

    #[test]
    fn test_state_deserialize_misuse() {
        unsafe {
            let state = adx_state();
            let bytes = tulip_state_serialize(
                CIndicatorId::Adx as u32,
                CStateFormat::Bincode as u32,
                state,
            );
            assert!(!bytes.ptr.is_null());
            let blob = std::slice::from_raw_parts(bytes.ptr, bytes.len).to_vec();

            // Truncated below header length
            assert!(tulip_state_deserialize(blob.as_ptr(), HEADER_LEN - 1).is_null());
            // Header only, empty payload: decodes nothing -> null
            assert!(tulip_state_deserialize(blob.as_ptr(), HEADER_LEN).is_null());

            // Corrupted magic
            let mut bad = blob.clone();
            bad[0] = b'X';
            assert!(tulip_state_deserialize(bad.as_ptr(), bad.len()).is_null());

            // Unknown schema version (the retired v1 layout must be rejected)
            let mut bad = blob.clone();
            bad[4] = 1;
            assert!(tulip_state_deserialize(bad.as_ptr(), bad.len()).is_null());

            // Unknown format byte
            let mut bad = blob.clone();
            bad[5] = 7;
            assert!(tulip_state_deserialize(bad.as_ptr(), bad.len()).is_null());

            // Unknown/corrupted indicator name
            let mut bad = blob.clone();
            bad[6] = b'q';
            assert!(tulip_state_deserialize(bad.as_ptr(), bad.len()).is_null());

            // Name field with trailing junk after the NUL padding is not a
            // name match (only the exact unpadded name is).
            let mut bad = blob.clone();
            bad[9] = b'x'; // "adx\0..." -> "adx\0x"
            assert!(tulip_state_deserialize(bad.as_ptr(), bad.len()).is_null());

            // Structurally invalid payload: too short to decode (note:
            // random byte flips are NOT rejected -- this state is pure
            // f64/usize aggregates, and any bit pattern is a valid f64).
            let mut bad = blob.clone();
            bad.truncate(HEADER_LEN + 1);
            assert!(tulip_state_deserialize(bad.as_ptr(), bad.len()).is_null());

            crate::adx::adx_state_free(state);
            tulip_ffi_bytes_free(bytes);
        }
    }

