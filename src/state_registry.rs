    /// MUST match build.rs's fnv1a32 exactly; pinned by the official FNV
    /// reference vectors below so drift is impossible.
    fn fnv1a32(name: &[u8]) -> u32 {
        let mut hash: u32 = 0x811c9dc5;
        for &b in name {
            hash ^= b as u32;
            hash = hash.wrapping_mul(0x01000193);
        }
        hash
    }

    #[test]
    fn test_fnv1a32_pinned_to_reference_vectors() {
        assert_eq!(fnv1a32(b""), 0x811c_9dc5);
        assert_eq!(fnv1a32(b"a"), 0xe40c_292c);
        assert_eq!(fnv1a32(b"foobar"), 0xbf9c_f968);
    }

    #[test]
    fn test_generated_ids_match_hash_of_name() {
        for &id in CIndicatorId::ALL {
            assert_eq!(
                id as u32,
                fnv1a32(id.name()),
                "discriminant for {:?} is not fnv1a32 of its name",
                id
            );
            // TryFrom round-trips for every generated id...
            assert_eq!(CIndicatorId::try_from(id as u32), Ok(id));
            // ...and the name lookup agrees with the identity.
            assert_eq!(CIndicatorId::from_name(id.name()), Some(id));
        }
        // A few values outside the (hash-shaped, hence non-contiguous) id
        // space must be rejected, including the old positional ids.
        assert!(CIndicatorId::try_from(0).is_err());
        assert!(CIndicatorId::try_from(999).is_err());
        assert!(CIndicatorId::try_from(u32::MAX).is_err());
    }

    fn adx_state() -> *mut c_void {
        unsafe {
            let data_len = 60usize;
            let high: Vec<f64> = build_synthetic_data(data_len, 2);
            let low: Vec<f64> = build_synthetic_data(data_len, 0);
            let close: Vec<f64> = build_synthetic_data(data_len, 1);
            let inputs_ptr: [*const f64; 3] = [high.as_ptr(), low.as_ptr(), close.as_ptr()];
            let options: [f64; 1] = [14.0];
            let result = crate::adx::adx_indicator(
                inputs_ptr.as_ptr(),
                data_len,
                options.as_ptr(),
                std::ptr::null(),
                0,
            );
            assert_eq!(result.error, crate::common::CIndicatorError::Ok);
            result.state
        }
    }

    /// Serialize `state`, deserialize the blob, run an identical batch on
    /// the original and restored handles, and assert bar-for-bar equality.
    fn roundtrip_batch_matches(id: u32, fmt: u32, state: *mut c_void, lanes: usize) {
        unsafe {
            let bytes = tulip_state_serialize(id, fmt, state);
            assert!(!bytes.ptr.is_null());
            assert!(bytes.len > HEADER_LEN);

            let restored = tulip_state_deserialize(bytes.ptr, bytes.len);
            assert!(!restored.is_null());

            let extra_len = 10usize;
            let a: Vec<Vec<f64>> = (0..lanes)
                .map(|k| build_synthetic_data(extra_len, k))
                .collect();
            let ptrs: Vec<*const f64> = a.iter().map(|v| v.as_ptr()).collect();
            let orig = crate::adx::adx_batch(state, ptrs.as_ptr(), extra_len, std::ptr::null(), 0);
            let rest =
                crate::adx::adx_batch(restored, ptrs.as_ptr(), extra_len, std::ptr::null(), 0);
            assert_eq!(orig.error, crate::common::CIndicatorError::Ok);
            assert_eq!(rest.error, crate::common::CIndicatorError::Ok);
            assert_eq!(orig.num_outputs, rest.num_outputs);

            let lens_o = std::slice::from_raw_parts(orig.output_lens, orig.num_outputs);
            let lens_r = std::slice::from_raw_parts(rest.output_lens, rest.num_outputs);
            assert_eq!(lens_o, lens_r);
            let rows_o = std::slice::from_raw_parts(orig.outputs, orig.num_outputs);
            let rows_r = std::slice::from_raw_parts(rest.outputs, rest.num_outputs);
            for i in 0..orig.num_outputs {
                let vo = std::slice::from_raw_parts(rows_o[i], lens_o[i]);
                let vr = std::slice::from_raw_parts(rows_r[i], lens_r[i]);
                for j in 0..vo.len() {
                    assert_eq!(vo[j].to_bits(), vr[j].to_bits());
                }
            }

            crate::common::tulip_ffi_batch_result_free(orig);
            crate::common::tulip_ffi_batch_result_free(rest);
            crate::adx::adx_state_free(restored);
            tulip_ffi_bytes_free(bytes);
        }
    }

