//! Generic indicator-state serialization/deserialization for FFI.
//!
//! This module provides indicator-agnostic entry points to serialize and
//! deserialize the opaque state handles returned by `<name>_indicator()`,
//! so bindings in GC'd languages can persist streaming state (DB rows,
//! files) as opaque byte blobs and resume them later.
//!
//! Wire format (TRFS schema 2): fixed header followed by the encoded state:
//!   - magic: `[u8; 4]` = `*b"TRFS"` (Tulip FFI State)
//!   - schema version: `u8` = 2
//!   - format: `u8` (a `CStateFormat` discriminant)
//!   - indicator name: `[u8; 32]`, the canonical lowercase name,
//!     zero-padded (e.g. `b"adx"`)
//!   - payload: the encoded state, per `format`
//!
//! The NAME field -- not the numeric id -- is the authoritative wire
//! identity: deserialization dispatches entirely on the embedded name, so
//! `tulip_state_deserialize()` takes no indicator argument and a blob can
//! never be "cross-fed" a wrong type by argument mistake.
//!
//! `CIndicatorId`, its `TryFrom<u32>`, its name lookups and the three
//! concrete-type dispatchers are GENERATED by `build.rs` (see
//! `state_ids_generated.rs`) from the crate's indicator list. Ids are
//! `fnv1a32(<lowercase name>)`, a pure function of identity: adding or
//! removing indicators never renumbers an existing id, and list order
//! carries no wire meaning.
//!
//! Format selector is `CStateFormat` (Bincode or Json). The public API uses
//! `format: u32` parameters for C ABI compatibility; validation goes through
//! `CStateFormat::try_from(format)` so adding variants yields one obvious
//! dispatch point.
//!
//! # Format notes
//! - **bincode (`CStateFormat::Bincode`)**: Recommended for persistence.
//!   Compact, handles all f64 values including NaN/Inf.
//! - **JSON (`CStateFormat::Json`)**: Human-readable, for debugging and
//!   inspection. Fails on non-finite f64s (serde_json limitation).
//!
//! # Versioning
//! Schema 2 is the first published wire format (no deployed schema-1
//! blobs exist); blobs with any other version byte are rejected. If the
//! hash function or header layout ever changes, bump the version and
//! reject the old range here.

use serde::de::DeserializeOwned;
use serde::Serialize;
use std::os::raw::c_void;

/// Wire format selector for `tulip_state_serialize` (and the `format` byte
/// embedded in the blob header).
#[repr(u32)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CStateFormat {
    /// Compact binary encoding; recommended for persistence. Handles all
    /// f64 values including NaN/Inf.
    Bincode = 0,
    /// Human-readable JSON via serde_json, for debugging/inspection only:
    /// fails (null return) on non-finite f64s.
    Json = 1,
}

impl TryFrom<u32> for CStateFormat {
    type Error = ();

    fn try_from(value: u32) -> Result<Self, Self::Error> {
        match value {
            0 => Ok(CStateFormat::Bincode),
            1 => Ok(CStateFormat::Json),
            _ => Err(()),
        }
    }
}

/// Wire format magic bytes.
const MAGIC: [u8; 4] = *b"TRFS";

/// Current schema version.
const SCHEMA_VERSION: u8 = 2;

/// Width of the zero-padded indicator-name field. MUST stay in sync with
/// `NAME_FIELD` in `build.rs` (which asserts every name fits it).
const NAME_FIELD: usize = 32;

/// Total fixed header size: magic(4) + version(1) + format(1) + name(32).
const HEADER_LEN: usize = 4 + 1 + 1 + NAME_FIELD;

// The generated enum CIndicatorId + TryFrom<u32> + ALL/name()/from_name()
// + serialize_dispatch()/deserialize_dispatch()/clone_dispatch(), one arm
// per indicator the crate wraps. Regenerated on every build; see build.rs.
include!("state_ids_generated.rs");

/// Build the fixed header for a serialized state blob.
fn header_bytes(id: CIndicatorId, fmt: CStateFormat) -> [u8; HEADER_LEN] {
    let mut header = [0u8; HEADER_LEN];
    header[0..4].copy_from_slice(&MAGIC);
    header[4] = SCHEMA_VERSION;
    header[5] = fmt as u8;
    let name = id.name();
    // build.rs asserts every name fits NAME_FIELD at generation time, so
    // a name here is always short enough; debug_assert documents the rest.
    debug_assert!(name.len() <= NAME_FIELD);
    header[6..6 + name.len()].copy_from_slice(name);
    header
}

/// Strip the zero padding from a header name field.
fn trim_name(name: &[u8]) -> &[u8] {
    let end = name.iter().rposition(|&b| b != 0).map_or(0, |i| i + 1);
    &name[..end]
}

/// Serialize a boxed indicator state into an opaque byte blob.
/// `state` is the `*mut c_void` handle from `<name>_indicator()` (READ ONLY
/// -- the state is not consumed). `indicator` must be the matching
/// `C_INDICATOR_ID_*` constant for that state's type. Returns
/// `CBytes { ptr: null }` on error. Free the blob with
/// `tulip_ffi_bytes_free`.
///
/// The blob is self-describing (it embeds the indicator name); pass it
/// straight to `tulip_state_deserialize` with no further arguments.
///
/// `format`: a `CStateFormat` discriminant (0 = Bincode, 1 = Json).
///
/// # Safety
/// `state` must be null, or a valid pointer previously returned by an
/// indicator's `<name>_indicator()` function (or `tulip_state_deserialize`/
/// `tulip_state_clone`) that matches `indicator` and has not been passed to
/// `<name>_state_free()` yet. The state is read-only (not consumed).
#[no_mangle]
pub unsafe extern "C" fn tulip_state_serialize(
    indicator: u32,
    format: u32,
    state: *const c_void,
) -> crate::common::CBytes {
    if state.is_null() {
        return crate::common::CBytes::null();
    }
    let id = match CIndicatorId::try_from(indicator) {
        Ok(id) => id,
        Err(_) => return crate::common::CBytes::null(),
    };
    let fmt = match CStateFormat::try_from(format) {
        Ok(fmt) => fmt,
        Err(_) => return crate::common::CBytes::null(),
    };
    serialize_dispatch(id, fmt, state)
}

/// Private helper for `serialize_dispatch` (generic over the concrete type).
/// All argument validation has already happened at this point.
unsafe fn serialize_state<S: Serialize>(
    id: CIndicatorId,
    fmt: CStateFormat,
    state: *const c_void,
) -> crate::common::CBytes {
    let s: &S = &*(state as *const S);
    let mut out: Vec<u8> = header_bytes(id, fmt).to_vec();
    let body = match fmt {
        CStateFormat::Bincode => bincode::serialize(s).ok(),
        CStateFormat::Json => serde_json::to_vec(s).ok(),
    };
    match body {
        Some(b) => {
            out.extend_from_slice(&b);
            crate::common::CBytes::from_vec(out)
        }
        None => crate::common::CBytes::null(),
    }
}

/// Reconstruct a boxed state from a blob produced by `tulip_state_serialize`.
/// The blob's header identifies the indicator (by name) and the encoding
/// format -- there is no indicator argument to mismatch. The returned
/// `*mut c_void` is indistinguishable from a fresh `<name>_indicator()`
/// state handle: use with `<name>_batch()` and release with
/// `<name>_state_free()`.
///
/// Returns null on error: null input, truncated data, bad magic, unknown
/// schema version, unknown format byte, unknown indicator name, or a
/// payload that fails to decode. Malformed input can never cause UB or a
/// panic -- only a null return.
///
/// # Safety
/// `bytes` must be null, or point to `len` readable bytes. Memory safety
/// holds for *any* contents; the validity requirement is only that the
/// pointer/len pair is dereferenceable.
#[no_mangle]
pub unsafe extern "C" fn tulip_state_deserialize(bytes: *const u8, len: usize) -> *mut c_void {
    if bytes.is_null() || len < HEADER_LEN {
        return std::ptr::null_mut();
    }

    let header: [u8; HEADER_LEN] = match std::slice::from_raw_parts(bytes, HEADER_LEN).try_into() {
        Ok(h) => h,
        Err(_) => return std::ptr::null_mut(), // unreachable given len check
    };

    if header[0..4] != MAGIC {
        return std::ptr::null_mut();
    }
    if header[4] != SCHEMA_VERSION {
        return std::ptr::null_mut();
    }
    let fmt = match CStateFormat::try_from(header[5] as u32) {
        Ok(fmt) => fmt,
        Err(_) => return std::ptr::null_mut(),
    };
    let id = match CIndicatorId::from_name(trim_name(&header[6..])) {
        Some(id) => id,
        None => return std::ptr::null_mut(),
    };

    deserialize_dispatch(id, fmt, bytes.add(HEADER_LEN), len - HEADER_LEN)
}

/// Private helper for `deserialize_dispatch` (generic over the concrete
/// type). Receives only the payload; the header (magic, version, format,
/// name) was validated by `tulip_state_deserialize`.
unsafe fn deserialize_state<S: DeserializeOwned>(
    fmt: CStateFormat,
    payload: *const u8,
    payload_len: usize,
) -> *mut c_void {
    let payload_slice = std::slice::from_raw_parts(payload, payload_len);
    let state: S = match fmt {
        CStateFormat::Bincode => match bincode::deserialize(payload_slice) {
            Ok(s) => s,
            Err(_) => return std::ptr::null_mut(),
        },
        CStateFormat::Json => match serde_json::from_slice(payload_slice) {
            Ok(s) => s,
            Err(_) => return std::ptr::null_mut(),
        },
    };
    Box::into_raw(Box::new(state)) as *mut c_void
}

/// Clone a boxed indicator state directly via Rust's `Clone` (core state
/// types all derive it -- no serde round-trip involved). Returns null on
/// error (null state, unknown indicator).
/// The cloned state is independent: use with `<name>_batch()` and release
/// with `<name>_state_free()`.
///
/// # Safety
/// `state` must be null, or a valid pointer previously returned by an
/// indicator's `<name>_indicator()` function (or `tulip_state_deserialize`/
/// `tulip_state_clone`) that matches `indicator` and has not been passed to
/// `<name>_state_free()` yet.
#[no_mangle]
pub unsafe extern "C" fn tulip_state_clone(indicator: u32, state: *const c_void) -> *mut c_void {
    if state.is_null() {
        return std::ptr::null_mut();
    }
    let id = match CIndicatorId::try_from(indicator) {
        Ok(id) => id,
        Err(_) => return std::ptr::null_mut(),
    };
    clone_dispatch(id, state)
}

/// Private helper for `clone_dispatch` (generic over the concrete type).
unsafe fn clone_state<S: Clone>(state: *const c_void) -> *mut c_void {
    let s: &S = &*(state as *const S);
    Box::into_raw(Box::new(s.clone())) as *mut c_void
}

